USE DATABASE FINLENS_DW;

-- A. Top stocks by 20-trading-session return.
WITH ranked AS (
  SELECT
    SYMBOL,
    TRADE_DATE,
    CLOSE_PRICE,
    LAG(CLOSE_PRICE, 20) OVER (PARTITION BY SYMBOL ORDER BY TRADE_DATE) AS CLOSE_20D_AGO
  FROM GOLD.FACT_STOCK_DAILY
)
SELECT SYMBOL, TRADE_DATE, CLOSE_PRICE,
       CLOSE_PRICE / NULLIF(CLOSE_20D_AGO, 0) - 1 AS RETURN_20D
FROM ranked
QUALIFY CLOSE_20D_AGO IS NOT NULL
ORDER BY RETURN_20D DESC
LIMIT 10;

-- B. Average daily return and volatility by ICB sector, last 60 observed rows per symbol.
WITH recent AS (
  SELECT f.SYMBOL, f.TRADE_DATE, f.DAILY_RETURN,
         ROW_NUMBER() OVER (PARTITION BY f.SYMBOL ORDER BY f.TRADE_DATE DESC) AS RN
  FROM GOLD.FACT_STOCK_DAILY f
  WHERE f.DAILY_RETURN IS NOT NULL
)
SELECT d.SECTOR_CODE, d.SECTOR_NAME,
       COUNT(*) AS OBSERVATIONS,
       AVG(r.DAILY_RETURN) AS AVG_DAILY_RETURN,
       STDDEV_SAMP(r.DAILY_RETURN) AS DAILY_RETURN_VOLATILITY
FROM recent r
JOIN GOLD.DIM_SYMBOL d ON r.SYMBOL = d.SYMBOL
WHERE r.RN <= 60
GROUP BY d.SECTOR_CODE, d.SECTOR_NAME
ORDER BY DAILY_RETURN_VOLATILITY DESC;

-- C. Compare selected stock(s) with VN-Index/VN30 daily return.
SELECT TRADE_DATE, SYMBOL, DAILY_RETURN
FROM GOLD.FACT_STOCK_DAILY
WHERE SYMBOL IN ('FPT', 'HPG', 'VCB')
  AND TRADE_DATE >= DATEADD(day, -90, CURRENT_DATE())
ORDER BY TRADE_DATE, SYMBOL;

SELECT TRADE_DATE, INDEX_SYMBOL, DAILY_RETURN
FROM GOLD.FACT_INDEX_DAILY
WHERE INDEX_SYMBOL IN ('VNINDEX', 'VN30')
  AND TRADE_DATE >= DATEADD(day, -90, CURRENT_DATE())
ORDER BY TRADE_DATE, INDEX_SYMBOL;

-- D. Bonds maturing in the next 180 days.
SELECT BOND_CODE, ISSUER, COUPON_RATE, MATURITY_DATE,
       OUTSTANDING_AMOUNT, BOND_TYPE, DAYS_TO_MATURITY, MATURITY_BUCKET
FROM GOLD.FACT_BOND_CURRENT
WHERE DAYS_TO_MATURITY BETWEEN 0 AND 180
ORDER BY MATURITY_DATE;

-- E. Data-quality exceptions in Silver stock prices.
SELECT DATA_QUALITY_STATUS, COUNT(*) AS ROWS
FROM SILVER.STOCK_OHLCV_DAILY
GROUP BY DATA_QUALITY_STATUS
ORDER BY ROWS DESC;

-- F. Latest ETL status by table.
SELECT TABLE_NAME, STATUS, SOURCE_ROWS, LOADED_ROWS, STARTED_AT, FINISHED_AT, ERROR_MESSAGE
FROM FINLENS_DW.OPS.ETL_RUN_LOG
QUALIFY ROW_NUMBER() OVER (PARTITION BY TABLE_NAME ORDER BY STARTED_AT DESC) = 1
ORDER BY TABLE_NAME;
