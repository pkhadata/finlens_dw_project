-- Run once in Snowflake Snowsight using a role with the required privileges.
CREATE WAREHOUSE IF NOT EXISTS FINLENS_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS FINLENS_DW;
CREATE SCHEMA IF NOT EXISTS FINLENS_DW.BRONZE;
CREATE SCHEMA IF NOT EXISTS FINLENS_DW.SILVER;
CREATE SCHEMA IF NOT EXISTS FINLENS_DW.GOLD;
CREATE SCHEMA IF NOT EXISTS FINLENS_DW.OPS;

CREATE TABLE IF NOT EXISTS FINLENS_DW.OPS.ETL_RUN_LOG (
    RUN_ID          VARCHAR(36),
    TABLE_NAME      VARCHAR(128),
    STATUS          VARCHAR(32),
    SOURCE_ROWS     NUMBER(38,0),
    LOADED_ROWS     NUMBER(38,0),
    STARTED_AT      TIMESTAMP_NTZ,
    FINISHED_AT     TIMESTAMP_NTZ,
    ERROR_MESSAGE   VARCHAR(4000)
);

USE WAREHOUSE FINLENS_WH;
USE DATABASE FINLENS_DW;
USE SCHEMA BRONZE;
