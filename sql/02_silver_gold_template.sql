USE DATABASE FINLENS_DW;

-- 1) SILVER.SECTORS: latest source record per sector code.
CREATE OR REPLACE TABLE SILVER.SECTORS AS
SELECT
    TO_VARCHAR(SECTOR_CODE) AS SECTOR_CODE,
    NULLIF(TRIM(TO_VARCHAR(SECTOR_NAME)), '') AS SECTOR_NAME,
    TRY_TO_NUMBER(SECTOR_LEVEL) AS SECTOR_LEVEL,
    TO_VARCHAR(PARENT_SECTOR_CODE) AS PARENT_SECTOR_CODE,
    _ETL_BATCH_ID,
    _ETL_LOADED_AT_UTC
FROM BRONZE.SECTORS
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY TO_VARCHAR(SECTOR_CODE)
    ORDER BY _ETL_LOADED_AT_UTC DESC
) = 1;

-- 2) SILVER.SYMBOLS: latest source record per symbol.
CREATE OR REPLACE TABLE SILVER.SYMBOLS AS
SELECT
    UPPER(TRIM(TO_VARCHAR(SYMBOL))) AS SYMBOL,
    UPPER(NULLIF(TRIM(TO_VARCHAR(EXCHANGE)), '')) AS EXCHANGE,
    NULLIF(TRIM(TO_VARCHAR(COMPANY_NAME)), '') AS COMPANY_NAME,
    TO_VARCHAR(SECTOR_CODE) AS SECTOR_CODE,
    _ETL_BATCH_ID,
    _ETL_LOADED_AT_UTC
FROM BRONZE.SYMBOLS
WHERE SYMBOL IS NOT NULL
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY UPPER(TRIM(TO_VARCHAR(SYMBOL)))
    ORDER BY _ETL_LOADED_AT_UTC DESC
) = 1;

-- 3) SILVER.STOCK_OHLCV_DAILY: standardized types, one symbol/date record.
CREATE OR REPLACE TABLE SILVER.STOCK_OHLCV_DAILY AS
SELECT
    UPPER(TRIM(TO_VARCHAR(SYMBOL))) AS SYMBOL,
    TRY_TO_DATE(TO_VARCHAR(DATE)) AS TRADE_DATE,
    TRY_TO_DECIMAL(TO_VARCHAR(OPEN), 18, 4) AS OPEN_PRICE,
    TRY_TO_DECIMAL(TO_VARCHAR(HIGH), 18, 4) AS HIGH_PRICE,
    TRY_TO_DECIMAL(TO_VARCHAR(LOW), 18, 4) AS LOW_PRICE,
    TRY_TO_DECIMAL(TO_VARCHAR(CLOSE), 18, 4) AS CLOSE_PRICE,
    TRY_TO_DECIMAL(TO_VARCHAR(VOLUME), 38, 0) AS VOLUME,
    CASE
      WHEN SYMBOL IS NULL OR DATE IS NULL OR CLOSE IS NULL THEN 'MISSING_KEY_OR_CLOSE'
      WHEN TRY_TO_DECIMAL(TO_VARCHAR(LOW), 18, 4) > TRY_TO_DECIMAL(TO_VARCHAR(HIGH), 18, 4) THEN 'INVALID_LOW_HIGH'
      WHEN TRY_TO_DECIMAL(TO_VARCHAR(OPEN), 18, 4) NOT BETWEEN TRY_TO_DECIMAL(TO_VARCHAR(LOW), 18, 4) AND TRY_TO_DECIMAL(TO_VARCHAR(HIGH), 18, 4) THEN 'OPEN_OUTSIDE_RANGE'
      WHEN TRY_TO_DECIMAL(TO_VARCHAR(CLOSE), 18, 4) NOT BETWEEN TRY_TO_DECIMAL(TO_VARCHAR(LOW), 18, 4) AND TRY_TO_DECIMAL(TO_VARCHAR(HIGH), 18, 4) THEN 'CLOSE_OUTSIDE_RANGE'
      WHEN TRY_TO_DECIMAL(TO_VARCHAR(VOLUME), 38, 0) < 0 THEN 'NEGATIVE_VOLUME'
      ELSE 'VALID'
    END AS DATA_QUALITY_STATUS,
    _ETL_BATCH_ID,
    _ETL_LOADED_AT_UTC
FROM BRONZE.STOCK_OHLCV_DAILY
WHERE SYMBOL IS NOT NULL AND DATE IS NOT NULL
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY UPPER(TRIM(TO_VARCHAR(SYMBOL))), TRY_TO_DATE(TO_VARCHAR(DATE))
    ORDER BY _ETL_LOADED_AT_UTC DESC
) = 1;

-- 4) SILVER.INDEX_OHLCV_DAILY: one index/date record.
CREATE OR REPLACE TABLE SILVER.INDEX_OHLCV_DAILY AS
SELECT
    UPPER(TRIM(TO_VARCHAR(SYMBOL))) AS INDEX_SYMBOL,
    TRY_TO_DATE(TO_VARCHAR(DATE)) AS TRADE_DATE,
    TRY_TO_DECIMAL(TO_VARCHAR(OPEN), 18, 4) AS OPEN_VALUE,
    TRY_TO_DECIMAL(TO_VARCHAR(HIGH), 18, 4) AS HIGH_VALUE,
    TRY_TO_DECIMAL(TO_VARCHAR(LOW), 18, 4) AS LOW_VALUE,
    TRY_TO_DECIMAL(TO_VARCHAR(CLOSE), 18, 4) AS CLOSE_VALUE,
    TRY_TO_DECIMAL(TO_VARCHAR(VOLUME), 38, 0) AS VOLUME,
    CASE
      WHEN SYMBOL IS NULL OR DATE IS NULL OR CLOSE IS NULL THEN 'MISSING_KEY_OR_CLOSE'
      WHEN TRY_TO_DECIMAL(TO_VARCHAR(LOW), 18, 4) > TRY_TO_DECIMAL(TO_VARCHAR(HIGH), 18, 4) THEN 'INVALID_LOW_HIGH'
      ELSE 'VALID'
    END AS DATA_QUALITY_STATUS,
    _ETL_BATCH_ID,
    _ETL_LOADED_AT_UTC
FROM BRONZE.INDEX_OHLCV_DAILY
WHERE SYMBOL IS NOT NULL AND DATE IS NOT NULL
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY UPPER(TRIM(TO_VARCHAR(SYMBOL))), TRY_TO_DATE(TO_VARCHAR(DATE))
    ORDER BY _ETL_LOADED_AT_UTC DESC
) = 1;

-- 5) SILVER.CORPORATE_BONDS: current outstanding-bond list, latest row per bond_code.
-- If the source has no bond_code, replace the partition key with a verified natural key.
CREATE OR REPLACE TABLE SILVER.CORPORATE_BONDS AS
SELECT
    UPPER(NULLIF(TRIM(TO_VARCHAR(BOND_CODE)), '')) AS BOND_CODE,
    NULLIF(TRIM(TO_VARCHAR(ISSUER)), '') AS ISSUER,
    TRY_TO_DECIMAL(TO_VARCHAR(COUPON_RATE), 9, 4) AS COUPON_RATE,
    TRY_TO_DATE(TO_VARCHAR(MATURITY_DATE)) AS MATURITY_DATE,
    TRY_TO_DECIMAL(TO_VARCHAR(OUTSTANDING_AMOUNT), 24, 4) AS OUTSTANDING_AMOUNT,
    NULLIF(TRIM(TO_VARCHAR(BOND_TYPE)), '') AS BOND_TYPE,
    _ETL_BATCH_ID,
    _ETL_LOADED_AT_UTC
FROM BRONZE.CORPORATE_BONDS
WHERE BOND_CODE IS NOT NULL
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY UPPER(TRIM(TO_VARCHAR(BOND_CODE)))
    ORDER BY _ETL_LOADED_AT_UTC DESC
) = 1;

-- Gold models (rebuildable demo implementation)
CREATE OR REPLACE TABLE GOLD.DIM_SECTOR AS
SELECT SECTOR_CODE, SECTOR_NAME, SECTOR_LEVEL, PARENT_SECTOR_CODE
FROM SILVER.SECTORS;

CREATE OR REPLACE TABLE GOLD.DIM_SYMBOL AS
SELECT
    s.SYMBOL,
    s.EXCHANGE,
    s.COMPANY_NAME,
    s.SECTOR_CODE,
    COALESCE(sec.SECTOR_NAME, 'UNKNOWN / UNMAPPED') AS SECTOR_NAME
FROM SILVER.SYMBOLS s
LEFT JOIN SILVER.SECTORS sec ON s.SECTOR_CODE = sec.SECTOR_CODE;

CREATE OR REPLACE TABLE GOLD.FACT_STOCK_DAILY AS
WITH base AS (
    SELECT * FROM SILVER.STOCK_OHLCV_DAILY WHERE DATA_QUALITY_STATUS = 'VALID'
), calc AS (
    SELECT
        SYMBOL, TRADE_DATE, OPEN_PRICE, HIGH_PRICE, LOW_PRICE, CLOSE_PRICE, VOLUME,
        LAG(CLOSE_PRICE) OVER (PARTITION BY SYMBOL ORDER BY TRADE_DATE) AS PREV_CLOSE
    FROM base
)
SELECT
    SYMBOL,
    TRADE_DATE,
    OPEN_PRICE,
    HIGH_PRICE,
    LOW_PRICE,
    CLOSE_PRICE,
    VOLUME,
    (CLOSE_PRICE * VOLUME) / 1000 AS EST_TRADING_VALUE_MILLION_VND,
    (CLOSE_PRICE / NULLIF(PREV_CLOSE, 0)) - 1 AS DAILY_RETURN,
    (HIGH_PRICE - LOW_PRICE) / NULLIF(PREV_CLOSE, 0) AS DAILY_RANGE_VS_PREV_CLOSE
FROM calc;

CREATE OR REPLACE TABLE GOLD.FACT_INDEX_DAILY AS
WITH base AS (
    SELECT * FROM SILVER.INDEX_OHLCV_DAILY WHERE DATA_QUALITY_STATUS = 'VALID'
), calc AS (
    SELECT
        INDEX_SYMBOL, TRADE_DATE, OPEN_VALUE, HIGH_VALUE, LOW_VALUE, CLOSE_VALUE, VOLUME,
        LAG(CLOSE_VALUE) OVER (PARTITION BY INDEX_SYMBOL ORDER BY TRADE_DATE) AS PREV_CLOSE
    FROM base
)
SELECT
    INDEX_SYMBOL, TRADE_DATE, OPEN_VALUE, HIGH_VALUE, LOW_VALUE, CLOSE_VALUE, VOLUME,
    (CLOSE_VALUE / NULLIF(PREV_CLOSE, 0)) - 1 AS DAILY_RETURN
FROM calc;

CREATE OR REPLACE TABLE GOLD.FACT_BOND_CURRENT AS
SELECT
    BOND_CODE,
    ISSUER,
    COUPON_RATE,
    MATURITY_DATE,
    OUTSTANDING_AMOUNT,
    BOND_TYPE,
    DATEDIFF('day', CURRENT_DATE(), MATURITY_DATE) AS DAYS_TO_MATURITY,
    CASE
      WHEN MATURITY_DATE < CURRENT_DATE() THEN 'PAST_DUE'
      WHEN MATURITY_DATE <= DATEADD('day', 30, CURRENT_DATE()) THEN 'DUE_0_30_DAYS'
      WHEN MATURITY_DATE <= DATEADD('day', 90, CURRENT_DATE()) THEN 'DUE_31_90_DAYS'
      WHEN MATURITY_DATE <= DATEADD('day', 180, CURRENT_DATE()) THEN 'DUE_91_180_DAYS'
      ELSE 'DUE_AFTER_180_DAYS'
    END AS MATURITY_BUCKET
FROM SILVER.CORPORATE_BONDS;

-- Optional date dimension based on observed stock/index trading dates.
CREATE OR REPLACE TABLE GOLD.DIM_DATE AS
WITH observed_dates AS (
    SELECT TRADE_DATE AS D FROM SILVER.STOCK_OHLCV_DAILY
    UNION
    SELECT TRADE_DATE AS D FROM SILVER.INDEX_OHLCV_DAILY
), bounds AS (
    SELECT MIN(D) AS START_DATE, MAX(D) AS END_DATE FROM observed_dates
), generated AS (
    SELECT DATEADD(day, SEQ4(), START_DATE) AS CALENDAR_DATE, END_DATE
    FROM bounds, TABLE(GENERATOR(ROWCOUNT => 20000))
    WHERE START_DATE IS NOT NULL
)
SELECT
    TO_NUMBER(TO_CHAR(CALENDAR_DATE, 'YYYYMMDD')) AS DATE_KEY,
    CALENDAR_DATE,
    YEAR(CALENDAR_DATE) AS YEAR,
    QUARTER(CALENDAR_DATE) AS QUARTER,
    MONTH(CALENDAR_DATE) AS MONTH,
    MONTHNAME(CALENDAR_DATE) AS MONTH_NAME,
    DAY(CALENDAR_DATE) AS DAY_OF_MONTH,
    DAYOFWEEKISO(CALENDAR_DATE) AS DAY_OF_WEEK_ISO,
    IFF(DAYOFWEEKISO(CALENDAR_DATE) IN (6, 7), TRUE, FALSE) AS IS_WEEKEND
FROM generated
WHERE CALENDAR_DATE <= END_DATE;
